<?php

/**
 * Logs 日志配置文件
 *
 * 使用方式：
 * 所有选项均为可选，未设置的键将保持 Logs 类的默认值。
 */
return [
    /*
    |--------------------------------------------------------------------------
    | 日志根目录
    |--------------------------------------------------------------------------
    | 必须为已存在的绝对路径且可写。日志文件按 年月/日.log 组织。
    | 留空或不设置时，自动探测框架的 runtime 目录。
    */
    'base_path' => '',

    /*
    |--------------------------------------------------------------------------
    | 最低日志级别
    |--------------------------------------------------------------------------
    | 支持字符串或数字：
    |   字符串：'debug' | 'info' | 'notice' | 'warning' | 'error' | 'critical' | 'alert' | 'emergency'
    |   数字：  100 | 200 | 250 | 300 | 400 | 500 | 550 | 600
    | 低于此级别的日志将被忽略。默认 'info'。
    */
    'min_level' => 'info',

    /*
    |--------------------------------------------------------------------------
    | GC 上下文过期时间（秒）
    |--------------------------------------------------------------------------
    | 常驻进程（Webman / Workerman / Swoole）中，协程上下文超过此时间会被自动回收。
    | 设为 0 表示永不过期。默认 300 秒。
    */
    'gc_ttl' => 300,

    /*
    |--------------------------------------------------------------------------
    | GC 上下文数量硬上限
    |--------------------------------------------------------------------------
    | 上下文数量超过此值后触发应急清理（配合 gc_emergency_ttl）。
    | 默认 2048。
    */
    'gc_hard_limit' => 2048,

    /*
    |--------------------------------------------------------------------------
    | GC 应急清理时间阈值（秒）
    |--------------------------------------------------------------------------
    | 仅当上下文数量超过硬上限时生效：超过该时长的上下文会被优先清理。
    | 默认 300 秒。
    */
    'gc_emergency_ttl' => 300,

    /*
    |--------------------------------------------------------------------------
    | 敏感字段脱敏键名
    |--------------------------------------------------------------------------
    | 上下文数组中键名命中此列表（不区分大小写）时，值替换为 '***'。
    | 设为空数组 [] 关闭脱敏。
    */
    'sensitive_keys' => [
        'password',
        'passwd',
        'secret',
        'token',
        'authorization',
        'api_key',
        'access_token',
        'refresh_token',
    ],

    /*
    |--------------------------------------------------------------------------
    | 敏感键名匹配模式
    |--------------------------------------------------------------------------
    | 'contains' — 子串匹配（默认，兼容旧行为），如 'secret' 匹配 'my_secret_key'
    | 'exact'    — 精确匹配，如 'secret' 只匹配键名恰好为 'secret' 的字段
    */
    'sensitive_key_match_mode' => 'contains',

    /*
    |--------------------------------------------------------------------------
    | 消息控制字符过滤
    |--------------------------------------------------------------------------
    | 开启后会清除日志消息中的 \x00-\x08, \x0B, \x0C, \x0E-\x1F, \x7F 等控制字符。
    | 默认 true。
    */
    'sanitize_message' => true,

    /*
    |--------------------------------------------------------------------------
    | 展开异常堆栈参数值
    |--------------------------------------------------------------------------
    | 开启后异常堆栈中每帧的调用参数会展开具体值，便于调试但可能泄漏敏感信息。
    | 默认 false（仅输出参数类型）。
    */
    'expand_trace_args' => false,

    /*
    |--------------------------------------------------------------------------
    | 高熵字符串自动脱敏
    |--------------------------------------------------------------------------
    | 开启后对异常属性中的长高熵字母数字串（如随机 token）自动替换为 ***(high entropy)。
    | Bearer / JWT 等固定格式始终脱敏，不受此开关影响。
    | 默认 false。
    */
    'auto_mask_high_entropy_strings' => false,

    /*
    |--------------------------------------------------------------------------
    | 关键指标统计
    |--------------------------------------------------------------------------
    | 开启后统计上下文数量（峰值）、写入延迟（微秒）、成功轮转次数与轮转锁失败次数，
    | 可通过 Logs::getMetrics() 查询，供监控告警使用。
    | 默认 false，避免热路径额外开销。
    */
    'enable_metrics' => false,
];
